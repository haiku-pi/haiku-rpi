#!/usr/bin/env bash
# flashlane-server.sh up|down|status — the Pi LAN DHCP+TFTP server for the Linux flash lane
# (TFTP root artifacts/flashlane/tftp, from scripts/flashlane-build.sh) plus an HTTP server on
# $PI_LAN_HOST:$FLASHLANE_PORT serving artifacts/flashlane/www (job.txt + the image).
#
# Only one DHCP server may run on the Pi LAN: `up` stops the peer project's netboot server
# first. Callers hold the bench lock (scripts/lib/bench.sh) and restore the peer afterwards.
# dnsmasq binds the Pi LAN interface only, so it never answers on the lab LAN.
set -euo pipefail
. "$(dirname "$0")/lib/bench.sh"
st="$HAIKU_RPI_ROOT/artifacts/flashlane/state"
www="$HAIKU_RPI_ROOT/artifacts/flashlane/www"
tftp="$HAIKU_RPI_ROOT/artifacts/flashlane/tftp"
mkdir -p "$st" "$www"

stop() {
	[ -f "$st/dnsmasq.pid" ] && sudo kill "$(cat "$st/dnsmasq.pid")" 2>/dev/null || true
	[ -f "$st/http.pid" ] && kill "$(cat "$st/http.pid")" 2>/dev/null || true
	rm -f "$st/dnsmasq.pid" "$st/http.pid"
}

case "${1:-}" in
up)
	"$HAIKU_RPI_ROOT/scripts/flashlane-build.sh" >/dev/null	# ~1 s; always current
	stop
	[ -x "$PEER_NETBOOT_DOWN" ] && (cd "$PEER_ROOT" && "$PEER_NETBOOT_DOWN") >/dev/null 2>&1 || true
	if pgrep -x dnsmasq -a | grep -q -- "$PI_LAN_IFACE\|pi-netboot\|netboot/dnsmasq.conf"; then
		echo "flashlane: another dnsmasq still serves the Pi LAN:" >&2; pgrep -x dnsmasq -a >&2; exit 1
	fi
	cat > "$st/dnsmasq.conf" <<CONF
# generated by flashlane-server.sh
interface=$PI_LAN_IFACE
bind-interfaces
listen-address=$PI_LAN_HOST
port=0
dhcp-range=10.42.0.10,10.42.0.20,12h
dhcp-option=3,$PI_LAN_HOST
dhcp-option=6,8.8.8.8
dhcp-option=66,$PI_LAN_HOST
log-dhcp
enable-tftp
tftp-root=$tftp
tftp-no-blocksize
log-facility=$st/dnsmasq.log
pid-file=$st/dnsmasq.pid
dhcp-leasefile=$st/dnsmasq.leases
user=$(id -un)
group=$(id -gn)
CONF
	: > "$st/dnsmasq.log"
	sudo dnsmasq -C "$st/dnsmasq.conf"
	setsid nohup "$PYTHON" -m http.server "$FLASHLANE_PORT" --bind "$PI_LAN_HOST" --directory "$www" \
		> "$st/http.log" 2>&1 < /dev/null 9>&- &
	echo $! > "$st/http.pid"
	sleep 1
	kill -0 "$(cat "$st/http.pid")" || { echo "flashlane: http server died: $(cat "$st/http.log")" >&2; exit 1; }
	echo "flashlane: up (dnsmasq pid $(cat "$st/dnsmasq.pid"), http $PI_LAN_HOST:$FLASHLANE_PORT)"
	;;
down) stop; echo "flashlane: down" ;;
status)
	for p in dnsmasq http; do
		if [ -f "$st/$p.pid" ] && kill -0 "$(cat "$st/$p.pid")" 2>/dev/null; then echo "$p: up"; else echo "$p: down"; fi
	done ;;
*) echo "usage: $0 up|down|status" >&2; exit 2 ;;
esac
